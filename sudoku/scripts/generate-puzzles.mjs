// Generates src/puzzles.js: 100 unique puzzles per level.
// sudoku-core rates a puzzle L1–L10 by the hardest human technique it needs
// (hidden single < naked single < pointing < pairs < X-Wing < Y-Wing < chains).
// Within a level, puzzles go from the lower band to the higher, then by solving effort,
// so #1 is the gentlest and #100 the toughest.
import { writeFileSync } from 'node:fs';
import { generate, analyze, solve, DIFFICULTIES } from 'sudoku-core';

const PER_LEVEL = 100;
const LEVELS = {
  easy: ['L2'], //          hidden singles, 42 givens
  medium: ['L3', 'L4'], //  naked singles, pointing
  hard: ['L5', 'L6'], //    naked/hidden pairs and triples, X-Wing, Swordfish
  expert: ['L7', 'L8'], //  Skyscraper, Kite, Y-Wing, W-Wing, colouring, unique rectangle
};

const digits = (board) => board.map((v) => v ?? 0).join('');

function puzzlesFor(bands) {
  const seen = new Map();
  for (const [k, band] of bands.entries()) {
    const quota = Math.round((PER_LEVEL * (k + 1)) / bands.length);
    for (let seed = 1; seen.size < quota; seed++) {
      let board;
      try {
        board = generate(band, { seed });
      } catch {
        continue; // no puzzle of this band from this seed
      }
      const key = digits(board);
      if (seen.has(key)) continue;
      const { score } = analyze(board);
      seen.set(key, { band, score, puzzle: key, solution: digits(solve(board).board) });
    }
    process.stdout.write(`${band} `);
  }
  const rank = (x) => DIFFICULTIES.indexOf(x.band);
  return [...seen.values()].sort((a, b) => rank(a) - rank(b) || a.score - b.score);
}

const data = Object.fromEntries(Object.entries(LEVELS).map(([level, bands]) => [level, puzzlesFor(bands)]));

const body = Object.entries(data)
  .map(([k, list]) => `  ${k}: [\n${list.map((x) => `    ['${x.puzzle}', '${x.solution}'],`).join('\n')}\n  ],`)
  .join('\n');
writeFileSync(
  new URL('../src/puzzles.js', import.meta.url),
  `// Generated by scripts/generate-puzzles.mjs — do not edit by hand.\n// Each entry: [puzzle, solution], 81 digits row by row, 0 = empty.\nexport const PUZZLES = {\n${body}\n};\n`,
);
