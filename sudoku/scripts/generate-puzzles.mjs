// Generates 9×9 puzzle sets with sudoku-core, which rates a puzzle L1–L10 by the hardest human
// technique it needs (hidden single < naked single < pointing < pairs < X-Wing < Y-Wing < chains).
// Within a level, puzzles go from the lower band to the higher, then by solving effort,
// so #1 is the gentlest.
//
//   node sudoku/scripts/generate-puzzles.mjs classic   → sudoku/puzzles.js       (4 levels × 100)
//   node sudoku/scripts/generate-puzzles.mjs easy      → sudoku-easy/puzzles.js  (L2, L3, L4: 1000 in all)
import { writeFileSync } from 'node:fs';
import { generate, analyze, solve, DIFFICULTIES } from 'sudoku-core';

const SETS = {
  classic: {
    file: '../../sudoku/puzzles.js',
    firstSeed: 1,
    levels: [
      { key: 'easy', name: '초급', bands: ['L2'], count: 100 }, //          hidden singles
      { key: 'medium', name: '중급', bands: ['L3', 'L4'], count: 100 }, //  naked singles, pointing
      { key: 'hard', name: '상급', bands: ['L5', 'L6'], count: 100 }, //    pairs and triples, X-Wing, Swordfish
      { key: 'expert', name: '최상급', bands: ['L7', 'L8'], count: 100 }, // Skyscraper, Kite, Y-Wing, W-Wing, colouring
    ],
  },
  easy: {
    file: '../../sudoku-easy/puzzles.js',
    firstSeed: 1_000_000, // away from the classic set's seeds so no puzzle repeats
    levels: [
      { key: 'l2', name: '레벨 2', note: '히든 싱글', bands: ['L2'], count: 334 },
      { key: 'l3', name: '레벨 3', note: '네이키드 싱글', bands: ['L3'], count: 333 },
      { key: 'l4', name: '레벨 4', note: '포인팅', bands: ['L4'], count: 333 },
    ],
  },
};

const set = SETS[process.argv[2]];
if (!set) throw new Error(`usage: generate-puzzles.mjs ${Object.keys(SETS).join('|')}`);

const digits = (board) => board.map((v) => v ?? 0).join('');

function puzzlesFor({ bands, count }) {
  const seen = new Map();
  for (const [k, band] of bands.entries()) {
    const quota = Math.round((count * (k + 1)) / bands.length);
    for (let seed = set.firstSeed; seen.size < quota; seed++) {
      let board;
      try {
        board = generate(band, { seed });
      } catch {
        continue; // no puzzle of this band from this seed
      }
      const key = digits(board);
      if (seen.has(key)) continue;
      const { score } = analyze(board);
      seen.set(key, { band, score, puzzle: key, solution: digits(solve(board).board) });
    }
    process.stdout.write(`${band} `);
  }
  const rank = (x) => DIFFICULTIES.indexOf(x.band);
  return [...seen.values()].sort((a, b) => rank(a) - rank(b) || a.score - b.score);
}

const levels = set.levels.map(({ key, name, note, ...spec }) => ({ key, name, note, puzzles: puzzlesFor(spec) }));
const body = levels
  .map(({ key, name, note, puzzles }) =>
    `  { key: '${key}', name: '${name}',${note ? ` note: '${note}',` : ''} puzzles: [\n${puzzles.map((x) => `    ['${x.puzzle}', '${x.solution}'],`).join('\n')}\n  ] },`)
  .join('\n');
writeFileSync(
  new URL(set.file, import.meta.url),
  `// Generated by sudoku/scripts/generate-puzzles.mjs — do not edit by hand.\n// Each puzzle: [puzzle, solution], digits row by row, 0 = empty.\nexport const LEVELS = [\n${body}\n];\n`,
);
console.log('\n' + levels.map((l) => `${l.name}: ${l.puzzles.length}`).join(', '));
