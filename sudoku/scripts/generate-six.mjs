// Generates sudoku6/puzzles.js: 500 6×6 puzzles (2×3 boxes), one solution each, solvable by
// singles alone. Givens fall evenly from 22 to 10 across the set; 100 puzzles per level.
// A puzzle is made by filling a random grid, removing givens while the solution stays unique,
// then adding back random givens up to the target count (more givens never break uniqueness).
// Run: node sudoku/scripts/generate-six.mjs
import { writeFileSync } from 'node:fs';
import { makeShape } from '../src/shape.js';

const SHAPE = makeShape(2, 3);
const { size: N, count: CELLS, peers, units } = SHAPE;
const TOTAL = 500;
const PER_LEVEL = 100;
const MOST = 22;
const FEWEST = 10;
const ALL = (1 << (N + 1)) - 2; // bits 1..N

let seed = 20261121;
const rng = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
const shuffle = (a) => { for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const bitsOf = (m) => [...Array(N).keys()].map((k) => k + 1).filter((d) => m & (1 << d));

function candidates(grid, i) {
  let m = ALL;
  for (const j of peers[i]) m &= ~(1 << grid[j]);
  return m;
}

// Counts solutions up to `limit`, filling the most constrained cell first.
function countSolutions(grid, limit = 2) {
  let best = -1, bestMask = 0, bestCount = N + 1;
  for (let i = 0; i < CELLS; i++) {
    if (grid[i]) continue;
    const m = candidates(grid, i);
    const c = bitsOf(m).length;
    if (c < bestCount) { best = i; bestMask = m; bestCount = c; }
    if (c === 0) return 0;
  }
  if (best === -1) return 1;
  let found = 0;
  for (const d of bitsOf(bestMask)) {
    grid[best] = d;
    found += countSolutions(grid, limit - found);
    grid[best] = 0;
    if (found >= limit) break;
  }
  return found;
}

function fullGrid() {
  const grid = new Array(CELLS).fill(0);
  const fill = (i) => {
    if (i === CELLS) return true;
    for (const d of shuffle(bitsOf(candidates(grid, i)))) {
      grid[i] = d;
      if (fill(i + 1)) return true;
    }
    grid[i] = 0;
    return false;
  };
  fill(0);
  return grid;
}

// Solves with naked and hidden singles only. Returns the number of hidden-single steps used,
// or -1 if singles get stuck (the puzzle would need a harder technique or a guess).
function singlesOnly(puzzle) {
  const grid = puzzle.slice();
  let hidden = 0;
  for (let progress = true; progress;) {
    progress = false;
    for (let i = 0; i < CELLS; i++) {
      if (grid[i]) continue;
      const ds = bitsOf(candidates(grid, i));
      if (ds.length === 1) { grid[i] = ds[0]; progress = true; }
    }
    if (progress) continue;
    for (const unit of units) {
      for (let d = 1; d <= N; d++) {
        if (unit.some((i) => grid[i] === d)) continue;
        const spots = unit.filter((i) => !grid[i] && candidates(grid, i) & (1 << d));
        if (spots.length === 1) { grid[spots[0]] = d; hidden++; progress = true; }
      }
    }
  }
  return grid.every(Boolean) ? hidden : -1;
}

function makePuzzle(givens) {
  for (;;) {
    const solution = fullGrid();
    const puzzle = solution.slice();
    const removed = [];
    for (const i of shuffle([...puzzle.keys()])) {
      puzzle[i] = 0;
      if (countSolutions(puzzle.slice()) === 1) removed.push(i);
      else puzzle[i] = solution[i];
    }
    const minimal = CELLS - removed.length;
    if (minimal > givens) continue;
    for (const i of shuffle(removed).slice(0, givens - minimal)) puzzle[i] = solution[i];
    const hidden = singlesOnly(puzzle);
    if (hidden === -1) continue;
    return { puzzle: puzzle.join(''), solution: solution.join(''), givens, hidden };
  }
}

const seen = new Set();
const all = [];
for (let k = 0; all.length < TOTAL; k++) {
  const target = Math.round(MOST - ((MOST - FEWEST) * all.length) / (TOTAL - 1));
  const p = makePuzzle(target);
  if (seen.has(p.puzzle)) continue;
  seen.add(p.puzzle);
  all.push(p);
}
all.sort((a, b) => b.givens - a.givens || a.hidden - b.hidden);

const levels = Array.from({ length: TOTAL / PER_LEVEL }, (_, k) => {
  const puzzles = all.slice(k * PER_LEVEL, (k + 1) * PER_LEVEL);
  return { key: `l${k + 1}`, name: `레벨 ${k + 1}`, note: `주어진 숫자 ${puzzles[0].givens}–${puzzles.at(-1).givens}개`, puzzles };
});
const body = levels
  .map(({ key, name, note, puzzles }) =>
    `  { key: '${key}', name: '${name}', note: '${note}', puzzles: [\n${puzzles.map((x) => `    ['${x.puzzle}', '${x.solution}'],`).join('\n')}\n  ] },`)
  .join('\n');
writeFileSync(
  new URL('../../sudoku6/puzzles.js', import.meta.url),
  `// Generated by sudoku/scripts/generate-six.mjs — do not edit by hand.\n// Each puzzle: [puzzle, solution], 36 digits row by row, 0 = empty.\nexport const LEVELS = [\n${body}\n];\n`,
);
