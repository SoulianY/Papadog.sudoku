// Generates src/puzzles.js: 100 unique puzzles per level.
// Difficulty is graded by QQwing from the solving techniques a puzzle requires:
//   SIMPLE (naked singles) → easy, EASY (hidden singles) → medium,
//   INTERMEDIATE (pairs, pointing, box/line) → hard, EXPERT (needs guessing) → expert.
import { writeFileSync } from 'node:fs';
import QQWing from 'qqwing';

const PER_LEVEL = 100;
const LEVELS = {
  easy: QQWing.Difficulty.SIMPLE,
  medium: QQWing.Difficulty.EASY,
  hard: QQWing.Difficulty.INTERMEDIATE,
  expert: QQWing.Difficulty.EXPERT,
};

const toDigits = (s) => s.replace(/\s/g, '').replace(/\./g, '0');

const buckets = Object.fromEntries(Object.keys(LEVELS).map((k) => [k, new Map()]));
const levelOf = Object.fromEntries(Object.entries(LEVELS).map(([k, v]) => [v, k]));
const q = new QQWing();
q.setPrintStyle(QQWing.PrintStyle.ONE_LINE);

while (Object.values(buckets).some((b) => b.size < PER_LEVEL)) {
  q.generatePuzzleSymmetry(QQWing.Symmetry.RANDOM);
  q.setRecordHistory(true);
  q.solve();
  const bucket = buckets[levelOf[q.getDifficulty()]];
  if (!bucket || bucket.size >= PER_LEVEL) continue;
  const puzzle = toDigits(q.getPuzzleString());
  bucket.set(puzzle, { puzzle, solution: toDigits(q.getSolutionString()) });
}

// Within a level, more givens first: puzzle #1 is the gentlest.
const givens = (p) => p.replace(/0/g, '').length;
const data = Object.fromEntries(
  Object.entries(buckets).map(([k, b]) => [k, [...b.values()].sort((a, c) => givens(c.puzzle) - givens(a.puzzle))]),
);

const body = Object.entries(data)
  .map(([k, list]) => `  ${k}: [\n${list.map((x) => `    ['${x.puzzle}', '${x.solution}'],`).join('\n')}\n  ],`)
  .join('\n');
writeFileSync(
  new URL('../src/puzzles.js', import.meta.url),
  `// Generated by scripts/generate-puzzles.mjs — do not edit by hand.\n// Each entry: [puzzle, solution], 81 digits row by row, 0 = empty.\nexport const PUZZLES = {\n${body}\n};\n`,
);
console.log(Object.entries(data).map(([k, l]) => `${k}: ${l.length}`).join(', '));
